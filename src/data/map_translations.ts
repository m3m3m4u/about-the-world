export function getTranslatedCountryName(idOrIso: string, rawName: string = ''): MultilingualText {
  const code = idOrIso.toLowerCase().trim();
  if (COUNTRIES_TRANSLATIONS[code]) {
    return COUNTRIES_TRANSLATIONS[code];
  }
  // Try matching rawName against known translations
  for (const item of Object.values(COUNTRIES_TRANSLATIONS)) {
    if (
      item.de.toLowerCase() === rawName.toLowerCase() ||
      item.en.toLowerCase() === rawName.toLowerCase() ||
      item.fr.toLowerCase() === rawName.toLowerCase() ||
      item.es.toLowerCase() === rawName.toLowerCase() ||
      item.it.toLowerCase() === rawName.toLowerCase()
    ) {
      return item;
    }
  }
  // Fallback
  return { de: rawName || idOrIso, en: rawName || idOrIso, fr: rawName || idOrIso, es: rawName || idOrIso, it: rawName || idOrIso };
}

